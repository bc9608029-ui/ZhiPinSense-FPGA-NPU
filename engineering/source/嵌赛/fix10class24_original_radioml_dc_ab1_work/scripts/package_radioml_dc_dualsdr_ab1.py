def build_dc_inputs_package():
    """Generate the 22-col dc-transport TX payload via scripts/export_radioml_dc_tx_payload.py
    into a fresh dir, generate route_d2_rf_manifest.tsv via the producer's build-frozen-dir,
    then package (480 .i16 + 22-col tx_manifest.tsv + route_d2 + sidecar)."""
    if not os.path.isdir(NPU_AB_INPUT_PACKAGE):
        sys.exit("missing npu-ab1 input_package: %s" % NPU_AB_INPUT_PACKAGE)
    work = tempfile.mkdtemp(prefix="pkg_dc_ab1_dc_input_")
    try:
        gen = os.path.join(work, "dc_tx_payload")
        r = subprocess.run(
            [sys.executable, "-I",
             os.path.join(ROOT, "scripts", "export_radioml_dc_tx_payload.py"),
             "--input-package", NPU_AB_INPUT_PACKAGE, "--out-dir", gen],
            capture_output=True, text=True)
        if r.returncode != 0 or "RADIOML_DC_TX_PAYLOAD_DONE" not in r.stdout:
            sys.exit("dc tx payload export failed: rc=%d\nstdout=%s\nstderr=%s"
                     % (r.returncode, r.stdout[-2000:], r.stderr[-2000:]))

        i16 = sorted(f for f in os.listdir(gen) if f.endswith(".i16"))
        if len(i16) != 480:
            sys.exit("expected 480 .i16 files from export, found %d" % len(i16))
        manifest = os.path.join(gen, "tx_manifest.tsv")
        with open(manifest, encoding="utf-8") as f:
            manifest_lines = f.read().rstrip("\n").split("\n")
        if len(manifest_lines) != 481:
            sys.exit("expected 481 lines in dc tx_manifest.tsv, got %d" % len(manifest_lines))
        if len(manifest_lines[0].split("\t")) != 22:
            sys.exit("dc tx_manifest.tsv is not 22 columns (got %d)"
                     % len(manifest_lines[0].split("\t")))

        # Generate route_d2_rf_manifest.tsv for dc-transport (producer's DC mapping).
        _run_producer_build_frozen_dir(gen, "dc-transport", gen)

        stage = os.path.join(work, DC_INPUTS_NAME)
        os.makedirs(stage, exist_ok=True)
        for n in i16:
            shutil.copy2(os.path.join(gen, n), os.path.join(stage, n))
        shutil.copy2(manifest, os.path.join(stage, "tx_manifest.tsv"))
        shutil.copy2(os.path.join(gen, "route_d2_rf_manifest.tsv"),
                     os.path.join(stage, "route_d2_rf_manifest.tsv"))
        n = write_sums(stage, DC_INPUTS_SUMS_NAME)
        tar_path = os.path.join(DIST, DC_INPUTS_NAME + ".tar.gz")
        build_tar_deterministic(stage, tar_path)
        print("determinism: OK (dc inputs tarball built twice, byte-identical)")
        shutil.copy2(os.path.join(stage, DC_INPUTS_SUMS_NAME),
                     os.path.join(DIST, DC_INPUTS_NAME + "_SHA256SUMS.txt"))
        ok, total, good = verify_tar_flat(tar_path, DC_INPUTS_SUMS_NAME)
        print("  %-40s files=%d ok=%d %s" % ("dc-ab1 dualsdr dc inputs", total, good,
                                              "PASS" if ok else "FAIL"))
        if not ok:
            sys.exit(1)
        print("  %-40s %d content-files  sha256=%s" %
              ("dc-ab1 dualsdr dc inputs", n, sha256_of(tar_path)))
        print("  %s" % tar_path)
    finally:
        shutil.rmtree(work, ignore_errors=True)


