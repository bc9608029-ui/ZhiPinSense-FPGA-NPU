def audit_vendor_singlesdr():
    """gate9_phase + board_gate9 must be byte-identical to the singlesdr fork (2-phase,
    single-SDR-only), and must NOT contain the dualsdr phase/wrapper."""
    bad = []
    for rel in VENDORED_FROM_SINGLESDR:
        src = os.path.join(SINGLESDR_DIR, rel.replace("/", os.sep))
        if not os.path.exists(src):
            bad.append(rel + " (missing in singlesdr fork)")
            continue
        txt = open(src, encoding="utf-8").read()
        if rel.endswith("gate9_phase.hpp"):
            if "radioml-original-singlesdr-ab-24class-bf16-fix10" not in txt:
                bad.append(rel + " missing singlesdr phase")
            if "radioml-original-dualsdr-ab-24class-bf16-fix10" in txt:
                bad.append(rel + " unexpectedly contains the dualsdr phase (want single-SDR only)")
        if rel.endswith("board_gate9_full_chain_rml23.cpp"):
            if "radioml_singlesdr_ab_runner.hpp" not in txt:
                bad.append(rel + " missing singlesdr runner include")
            if "radioml_dualsdr_ab_runner.hpp" in txt:
                bad.append(rel + " unexpectedly contains the dualsdr runner (want single-SDR only)")
    if bad:
        _fail("vendor-singlesdr audit", bad)
    print("vendor-singlesdr audit: OK (gate9_phase + board_gate9 = singlesdr fork, "
          "2-phase single-SDR-only)")


