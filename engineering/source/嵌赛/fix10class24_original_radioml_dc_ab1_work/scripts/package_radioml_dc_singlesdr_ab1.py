def build_direct_inputs_package():
    """Package the dualsdr fork's authoritative direct TX payload (18-col, 480 .i16) into
    the board's --input-dir data package.  Re-verifies every .i16 against the dualsdr
    fork's SHA256SUMS.txt, then re-packages VERBATIM with a fresh per-file sidecar."""
    tx = os.path.join(DUALSDR_DIR, "results", "tx_payload")
    if not os.path.isdir(tx):
        sys.exit("missing dualsdr tx_payload dir: %s" % tx)
    i16 = sorted(f for f in os.listdir(tx) if f.endswith(".i16"))
    if len(i16) != 480:
        sys.exit("expected 480 .i16 files in %s, found %d" % (tx, len(i16)))
    manifest = os.path.join(tx, "tx_manifest.tsv")
    if not os.path.isfile(manifest):
        sys.exit("missing tx_manifest.tsv in %s" % tx)
    with open(manifest, encoding="utf-8") as f:
        manifest_lines = f.read().rstrip("\n").split("\n")
    if len(manifest_lines) != 481:
        sys.exit("expected 481 lines (1 header + 480 data) in tx_manifest.tsv, got %d"
                 % len(manifest_lines))
    # direct = 18 columns exactly
    if len(manifest_lines[0].split("\t")) != 18:
        sys.exit("direct tx_manifest.tsv is not 18 columns (got %d)"
                 % len(manifest_lines[0].split("\t")))

    dual_sums = os.path.join(tx, "SHA256SUMS.txt")
    if not os.path.isfile(dual_sums):
        sys.exit("missing dualsdr SHA256SUMS.txt (payload authority) in %s" % tx)
    dual = {}
    for line in open(dual_sums, encoding="utf-8"):
        parts = line.split()
        if len(parts) >= 2:
            dual[parts[1]] = parts[0]
    for n in i16:
        if n not in dual or dual[n] != sha256_of(os.path.join(tx, n)):
            sys.exit("tx_payload %s does not match dualsdr SHA256SUMS.txt" % n)

    work = tempfile.mkdtemp(prefix="pkg_dc_ab1_direct_input_")
    try:
        stage = os.path.join(work, DIRECT_INPUTS_NAME)
        os.makedirs(stage, exist_ok=True)
        for n in i16:
            shutil.copy2(os.path.join(tx, n), os.path.join(stage, n))
        shutil.copy2(manifest, os.path.join(stage, "tx_manifest.tsv"))
        n = write_sums(stage, DIRECT_INPUTS_SUMS_NAME)
        tar_path = os.path.join(DIST, DIRECT_INPUTS_NAME + ".tar.gz")
        build_tar_deterministic(stage, tar_path)
        print("determinism: OK (direct inputs tarball built twice, byte-identical)")
        shutil.copy2(os.path.join(stage, DIRECT_INPUTS_SUMS_NAME),
                     os.path.join(DIST, DIRECT_INPUTS_NAME + "_SHA256SUMS.txt"))
        ok, total, good = verify_tar_flat(tar_path, DIRECT_INPUTS_SUMS_NAME)
        print("  %-40s files=%d ok=%d %s" % ("dc-ab1 direct inputs", total, good,
                                              "PASS" if ok else "FAIL"))
        if not ok:
            sys.exit(1)
        print("  %-40s %d content-files  sha256=%s" %
              ("dc-ab1 direct inputs", n, sha256_of(tar_path)))
        print("  %s" % tar_path)
    finally:
        shutil.rmtree(work, ignore_errors=True)


