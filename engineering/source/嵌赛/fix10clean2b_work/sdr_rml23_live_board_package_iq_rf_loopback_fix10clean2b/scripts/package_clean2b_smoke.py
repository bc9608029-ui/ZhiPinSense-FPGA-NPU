#!/usr/bin/env python3
"""Package the fix10clean2b-smoke delivery: clean-IQ dual-SDR 2-sample smoke.

fix10clean2b sits on top of the fix10prep2 authoritative tree (which is already
READY-FOR-BOARD-TEST) and adds ONE auditable path:

  clean2a-formal12000 sample (BPSK source_index=1500 / 4ASK source_index=500)
  -> D2 polyphase reconstruct (import-only, no Python re-implementation)
  -> quantized CI16 -> PC-TX Pluto -> 50-ohm coax -> board-RX Pluto
  -> sync/CFO/SRO/gain recovery -> board NPU24 -> 24->23 merge
  -> frozen-baseline comparison.

No real-time IQ crosses the network.  The recovery core, frame math, model,
weights, labels, preprocess, 24->23 mapping and the TCP state machine are all
UNCHANGED (red-line headers byte-identical to the fix10prep2 base).

The change set (the ONLY thing the patch carries):
  * new input-kind sidecar + tests + builders:
      board_package/iq_clean2b_sidecar.hpp
      host_tests/test_clean2b_smoke_d2.cpp, test_clean2b_smoke_protocol.cpp
      scripts/build_clean2b_smoke_d2.py, scripts/verify_clean2b_smoke_roundtrip.py
  * wiring + docs + packager:
      board_package/iq_pc_tx_board_rx_23class_fix10.hpp (4 edits)
      host_tools/pc_tx_sdr_fix10.py
      host_tests/build_host_tests.sh, host_tests/run_tests.sh
      scripts/package_clean2b_smoke.py
      docs/M29_RML23_FIX10CLEAN2B_DUAL_SDR_CLEAN_IQ_SMOKE_AUDIT.md
  * frozen-dir artifacts (12 files):
      clean2b_smoke/  (2 ci16 + 4 f32 + 4 TSV + 1 json + 1 SHA sidecar)

Produces, under F:/嵌赛/fix10clean2b_work/dist/:
  1. fix10clean2b_smoke_boardtest_full.tar.gz  (self-contained full tree + smoke)
  2. fix10clean2b_smoke_patch.tar.gz           (overlay patch: change set + smoke)
  3. fix10clean2b_smoke_boardtest_full_SHA256SUMS.txt  (per-file + package SHA)
  4. fix10clean2b_smoke_patch_SHA256SUMS.txt           (per-file + package SHA)

Fail-closed audits the packager runs BEFORE emitting anything:
  * RED-LINE headers (iq_rf_sync_recovery.hpp, iq_rf_training_frame.hpp,
    iq_digital_loopback.hpp, iq_rf_fix9r_baseline.hpp, iq_clean_baseline.hpp,
    iq_pc_tx_board_rx_transfer_fix10.hpp) byte-identical to the fix10prep2 base.
  * PROTECTED dirs (model/weights/labels/preprocess) byte-identical to base.
  * every quoted include of every new C++ file resolves inside the tree.
  * complete-delta: patch + fix10prep2 base reproduces the full tree.

Both tarballs are flat (no wrapping top dir): the full tar extracts board_package/
etc. straight into a fresh timestamped dir; the patch tar overlays straight onto a
copied fix10prep2 tree.  stdlib only; deterministic (uid/gid 0, mtime 0, sorted
entries, gzip level 9, mtime 0).

Run with:  python scripts/package_clean2b_smoke.py
"""

import gzip
import hashlib
import os
import re
import shutil
import sys
import tarfile
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), os.pardir))
WORK = os.path.abspath(os.path.join(ROOT, os.pardir))               # fix10clean2b_work
DIST = os.path.join(WORK, "dist")
CLEAN2B_SMOKE_DIR = os.path.join(WORK, "clean2b_smoke")

FULL_NAME = "fix10clean2b_smoke_boardtest_full"
FULL_SUMS_NAME = "SHA256SUMS.txt"
PATCH_NAME = "fix10clean2b_smoke_patch"
PATCH_SUMS_NAME = "FIX10CLEAN2B_PATCH_SHA256SUMS.txt"

EXTERNAL_FULL_SUMS = FULL_NAME + "_SHA256SUMS.txt"
EXTERNAL_PATCH_SUMS = PATCH_NAME + "_SHA256SUMS.txt"

# Directories never packaged (build products / python cache / output).
EXCLUDED_DIRS = {"host_tests/bin", "scripts/__pycache__", "dist", ".git",
                 "host_tools/.build_burst_cache", "host_tools/__pycache__"}

# Transient files never packaged (stale host-test logs; not regenerated by the
# build scripts, but a stray rerun with `tee` would recreate them).
EXCLUDED_FILES = {
    "host_tests/build_host_tests.log",
    "host_tests/run_tests.log",
}

# ---- the fix10clean2b-smoke change set (the ONLY thing the patch carries) ----
CLEAN2B_NEW_FILES = [
    "board_package/iq_clean2b_sidecar.hpp",
    "host_tests/test_clean2b_smoke_d2.cpp",
    "host_tests/test_clean2b_smoke_protocol.cpp",
    "scripts/build_clean2b_smoke_d2.py",
    "scripts/verify_clean2b_smoke_roundtrip.py",
    "scripts/package_clean2b_smoke.py",
    "docs/M29_RML23_FIX10CLEAN2B_DUAL_SDR_CLEAN_IQ_SMOKE_AUDIT.md",
]

CLEAN2B_MODIFIED_FILES = [
    "board_package/iq_pc_tx_board_rx_23class_fix10.hpp",
    "host_tools/pc_tx_sdr_fix10.py",
    "host_tests/build_host_tests.sh",
    "host_tests/run_tests.sh",
]

PATCH_FILES = CLEAN2B_NEW_FILES + CLEAN2B_MODIFIED_FILES
PATCH_FILES_SET = set(PATCH_FILES)

# The frozen-dir artifacts: exactly 12 files (2 ci16 + 4 f32 + 4 TSV + 1 json +
# 1 SHA sidecar), byte-for-byte the Step 1 output.  Copied as-is, never regenerated.
CLEAN2B_SMOKE_EXPECTED = 12

# Directories whose contents must be byte-identical to the fix10prep2 base.
PROTECTED_DIRS = ("model_rml23/", "model_12class/", "contracts/",
                  "deployment_golden/")

# RED LINE: these headers carry the recovery core, frame math, baseline loaders
# and the TCP state machine the fix10prep2 baseline proved; fix10clean2b-smoke
# must NOT have touched them.
RED_LINE_HEADERS = (
    "board_package/iq_rf_sync_recovery.hpp",
    "board_package/iq_rf_training_frame.hpp",
    "board_package/iq_digital_loopback.hpp",
    "board_package/iq_rf_fix9r_baseline.hpp",
    "board_package/iq_clean_baseline.hpp",
    "board_package/iq_pc_tx_board_rx_transfer_fix10.hpp",
)

_INCLUDE_RE = re.compile(r'^\s*#\s*include\s*"([^"]+)"')
_CPP_EXT = (".cpp", ".hpp", ".h", ".cc", ".cxx")


def sha256_of(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def write_bytes(path, data, mode=0o644):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)
    os.chmod(path, mode)


def list_files(stage):
    out = []
    for dirpath, dirnames, filenames in os.walk(stage):
        dirnames[:] = sorted(
            d for d in dirnames
            if os.path.relpath(os.path.join(dirpath, d), stage).replace(os.sep, "/")
            not in EXCLUDED_DIRS)
        for name in filenames:
            rel = os.path.relpath(os.path.join(dirpath, name), stage).replace(os.sep, "/")
            if rel not in EXCLUDED_FILES:
                out.append(rel)
    return sorted(out)


def write_sums(stage, sums_name):
    rels = [r for r in list_files(stage) if r != sums_name]
    lines = ["%s *%s\n" % (sha256_of(os.path.join(stage, rel.replace("/", os.sep))), rel)
             for rel in rels]
    write_bytes(os.path.join(stage, sums_name), "".join(sorted(lines)).encode("utf-8"))
    return len(rels)


def make_tar(stage, tar_path):
    """Deterministic flat tar: entries at top level (no wrapping dir), uid/gid 0,
    mtime 0, sorted, gzip level 9 with mtime 0."""
    raw = tar_path + ".tmp.tar"
    entries = []
    for dirpath, dirnames, filenames in os.walk(stage):
        dirnames[:] = sorted(
            d for d in dirnames
            if os.path.relpath(os.path.join(dirpath, d), stage).replace(os.sep, "/")
            not in EXCLUDED_DIRS)
        filenames.sort()
        for d in dirnames:
            entries.append((os.path.relpath(os.path.join(dirpath, d), stage)
                            .replace(os.sep, "/"), True))
        for name in filenames:
            rel = os.path.relpath(os.path.join(dirpath, name), stage).replace(os.sep, "/")
            if rel not in EXCLUDED_FILES:
                entries.append((rel, False))
    entries.sort(key=lambda e: e[0])

    with tarfile.open(raw, "w", format=tarfile.GNU_FORMAT) as t:
        for rel, is_dir in entries:
            full = os.path.join(stage, rel.replace("/", os.sep))
            info = t.gettarinfo(full, arcname=rel)
            info.uid = 0
            info.gid = 0
            info.uname = ""
            info.gname = ""
            info.mtime = 0
            info.mode = 0o755 if is_dir else (0o755 if rel.endswith(".sh") else 0o644)
            if is_dir:
                t.addfile(info)
            else:
                with open(full, "rb") as f:
                    t.addfile(info, f)

    with open(raw, "rb") as fin:
        with gzip.GzipFile(filename="", mode="wb", fileobj=open(tar_path, "wb"),
                           compresslevel=9, mtime=0) as gz:
            shutil.copyfileobj(fin, gz)
    os.remove(raw)


def verify_tar(tar_path, sums_name):
    """Independent unpack + per-file SHA check against the external sidecar's
    per-file lines (the package-SHA line is skipped)."""
    with tempfile.TemporaryDirectory() as td:
        with tarfile.open(tar_path, "r:gz") as t:
            t.extractall(td, filter="data")
        ok = 0
        bad = 0
        sums_path = os.path.join(td, sums_name)
        with open(sums_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.rstrip("\n")
                if not line:
                    continue
                hx, _, rel = line.partition(" *")
                p = os.path.join(td, rel.replace("/", os.sep))
                if rel.endswith(".tar.gz"):          # package self-SHA, not a file
                    continue
                if os.path.exists(p) and sha256_of(p) == hx:
                    ok += 1
                else:
                    bad += 1
                    print("  MISMATCH: %s" % rel, file=sys.stderr)
        return (bad == 0, ok + bad, ok)


def _cpp_includes(text):
    out = []
    for line in text.splitlines():
        m = _INCLUDE_RE.match(line)
        if m:
            out.append(m.group(1))
    return out


_INCLUDE_DIRS = ("board_package", "sdr_adapter", "ui_sw")


def audit_dependency_closure(full_dir, files=None, extra_roots=()):
    if files is None:
        files = PATCH_FILES
    roots = (full_dir,) + tuple(extra_roots)

    by_base = {}
    for root in roots:
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = sorted(
                d for d in dirnames
                if os.path.relpath(os.path.join(dirpath, d), root).replace(os.sep, "/")
                not in EXCLUDED_DIRS)
            for name in filenames:
                if name.endswith(_CPP_EXT):
                    p = os.path.join(dirpath, name)
                    by_base.setdefault(name, []).append(p)

    missing = set()
    for rel in files:
        if not rel.endswith(_CPP_EXT):
            continue
        abs_path = os.path.join(full_dir, rel.replace("/", os.sep))
        with open(abs_path, "r", encoding="utf-8", errors="replace") as f:
            includes = _cpp_includes(f.read())
        for inc in includes:
            cands = [os.path.normpath(os.path.join(os.path.dirname(abs_path), inc))]
            for root in roots:
                cands += [os.path.normpath(os.path.join(root, d, inc))
                          for d in _INCLUDE_DIRS]
            if not any(os.path.exists(c) for c in cands):
                base = os.path.basename(inc)
                hits = by_base.get(base, [])
                if len(hits) != 1:
                    missing.add(rel + " -> " + inc)
    return sorted(missing)


def audit_complete_delta(full_dir, base_dir, patch_files):
    patch_set = set(patch_files)
    violations = []
    for rel in list_files(full_dir):
        bf = os.path.join(base_dir, rel.replace("/", os.sep))
        ff = os.path.join(full_dir, rel.replace("/", os.sep))
        if os.path.exists(bf) and sha256_of(ff) == sha256_of(bf):
            continue   # unchanged fix10prep2 file
        if rel in patch_set:
            continue   # changed by the patch
        violations.append(rel)
    return sorted(violations)


def verify_protected_unchanged(full_dir, base_dir):
    violations = []
    for pdir in PROTECTED_DIRS:
        base_p = os.path.join(base_dir, pdir)
        full_p = os.path.join(full_dir, pdir)
        if not os.path.isdir(base_p):
            continue
        for dirpath, dirnames, filenames in os.walk(base_p):
            dirnames.sort()
            for name in sorted(filenames):
                bf = os.path.join(dirpath, name)
                rel = os.path.relpath(bf, base_dir).replace(os.sep, "/")
                ff = os.path.join(full_dir, rel.replace("/", os.sep))
                if not os.path.exists(ff) or sha256_of(ff) != sha256_of(bf):
                    violations.append(rel)
    return sorted(violations)


def verify_red_line_headers(full_dir, base_dir):
    violations = []
    for rel in RED_LINE_HEADERS:
        ff = os.path.join(full_dir, rel.replace("/", os.sep))
        bf = os.path.join(base_dir, rel.replace("/", os.sep))
        if not os.path.exists(bf):
            violations.append(rel + " (missing in base)")
        elif not os.path.exists(ff) or sha256_of(ff) != sha256_of(bf):
            violations.append(rel + " (differs from fix10prep2 base)")
    return sorted(violations)


def stage_copy(src_dir, dst_dir, rels):
    for rel in rels:
        src = os.path.join(src_dir, rel.replace("/", os.sep))
        write_bytes(os.path.join(dst_dir, rel.replace("/", os.sep)),
                    open(src, "rb").read())


def write_external_sums(tar_path, internal_sums_path, external_sums_path):
    """External sidecar = internal per-file sums + the package's own SHA."""
    with open(internal_sums_path, "r", encoding="utf-8") as f:
        body = f.read()
    line = "%s *%s\n" % (sha256_of(tar_path), os.path.basename(tar_path))
    write_bytes(external_sums_path, (body + line).encode("utf-8"))


def main():
    for rel in PATCH_FILES:
        if not os.path.exists(os.path.join(ROOT, rel.replace("/", os.sep))):
            sys.exit("missing clean2b file: %s" % rel)

    smoke_rels = list_files(CLEAN2B_SMOKE_DIR)
    if len(smoke_rels) != CLEAN2B_SMOKE_EXPECTED:
        sys.exit("clean2b_smoke/ has %d files, expected %d" %
                 (len(smoke_rels), CLEAN2B_SMOKE_EXPECTED))

    base_ref = os.path.abspath(os.path.join(
        WORK, os.pardir, "fix10prep2_work",
        "sdr_rml23_live_board_package_iq_rf_loopback_fix10prep2"))
    if not os.path.isdir(base_ref):
        sys.exit("fix10prep2 base tree missing: %s" % base_ref)

    work = tempfile.mkdtemp(prefix="pkg_clean2b_")
    try:
        full = os.path.join(work, "full")
        os.makedirs(full, exist_ok=True)
        tree_rels = [r for r in list_files(ROOT) if r != FULL_SUMS_NAME]
        for rel in tree_rels:
            src = os.path.join(ROOT, rel.replace("/", os.sep))
            dst = os.path.join(full, rel.replace("/", os.sep))
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(src, dst)
        for rel in smoke_rels:
            src = os.path.join(CLEAN2B_SMOKE_DIR, rel.replace("/", os.sep))
            dst = os.path.join(full, "clean2b_smoke", rel.replace("/", os.sep))
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(src, dst)

        # ---- RED LINE: recovery core + frame math + loaders + TCP state machine ----
        red_line_viol = verify_red_line_headers(full, base_ref)
        if red_line_viol:
            print("RED-LINE header audit FAILED:", file=sys.stderr)
            for v in red_line_viol:
                print("  " + v, file=sys.stderr)
            sys.exit(1)
        print("red-line header audit: OK (6 headers byte-identical to fix10prep2)")

        protected_viol = verify_protected_unchanged(full, base_ref)
        if protected_viol:
            print("protected-dir audit FAILED (model/weights/labels/preprocess "
                  "touched):", file=sys.stderr)
            for v in protected_viol:
                print("  " + v, file=sys.stderr)
            sys.exit(1)
        print("protected-dir audit: OK")

        missing = audit_dependency_closure(full, files=PATCH_FILES)
        if missing:
            print("dependency-closure audit FAILED:", file=sys.stderr)
            for v in missing:
                print("  " + v, file=sys.stderr)
            sys.exit(1)
        print("dependency-closure audit: OK")

        # clean2b_smoke/ files are NEW to the full tree (carried by the patch, in
        # addition to the 11 tree files) -- include them in the delta set so the
        # complete-delta audit sees them as patch-carried, not h5-drift.
        smoke_delta = ["clean2b_smoke/" + r for r in smoke_rels]
        delta_viol = audit_complete_delta(full, base_ref, PATCH_FILES + smoke_delta)
        if delta_viol:
            print("complete-delta audit FAILED (file changed vs fix10prep2 but not "
                  "in the patch):", file=sys.stderr)
            for v in delta_viol:
                print("  " + v, file=sys.stderr)
            sys.exit(1)
        print("complete-delta audit: OK (patch + fix10prep2 base reproduces the full tree)")

        # ---- 1. patch (change set + clean2b_smoke/, overlay-only) ----
        p = os.path.join(work, "patch")
        os.makedirs(p, exist_ok=True)
        stage_copy(ROOT, p, PATCH_FILES)
        stage_copy(CLEAN2B_SMOKE_DIR,
                   os.path.join(p, "clean2b_smoke"), smoke_rels)

        patch_missing = audit_dependency_closure(p, files=PATCH_FILES,
                                                 extra_roots=(base_ref,))
        if patch_missing:
            print("patch self-containment audit FAILED (patch cannot overlay onto "
                  "fix10prep2 alone):", file=sys.stderr)
            for v in patch_missing:
                print("  " + v, file=sys.stderr)
            sys.exit(1)
        print("patch self-containment audit: OK (patch overlays independently onto "
              "fix10prep2)")

        p_n = write_sums(p, PATCH_SUMS_NAME)
        os.makedirs(DIST, exist_ok=True)
        p_tar = os.path.join(DIST, PATCH_NAME + ".tar.gz")
        make_tar(p, p_tar)
        write_external_sums(p_tar, os.path.join(p, PATCH_SUMS_NAME),
                            os.path.join(DIST, EXTERNAL_PATCH_SUMS))

        # ---- 2. full (self-contained board-test tree + smoke) ----
        full_n = write_sums(full, FULL_SUMS_NAME)
        full_tar = os.path.join(DIST, FULL_NAME + ".tar.gz")
        make_tar(full, full_tar)
        write_external_sums(full_tar, os.path.join(full, FULL_SUMS_NAME),
                            os.path.join(DIST, EXTERNAL_FULL_SUMS))

        # ---- self-check (independent unpack + per-file SHA) ----
        print("== self-check ==")
        for label, tar, sums in [
            ("clean2b patch", p_tar, PATCH_SUMS_NAME),
            ("clean2b full", full_tar, FULL_SUMS_NAME),
        ]:
            ok, total, good = verify_tar(tar, sums)
            print("  %-16s files=%d ok=%d %s" % (label, total, good,
                                                 "PASS" if ok else "FAIL"))
            if not ok:
                sys.exit(1)

        print("== summary ==")
        for label, tar, n in [
            ("clean2b patch", p_tar, p_n),
            ("clean2b full", full_tar, full_n),
        ]:
            print("  %-16s %d content-files  sha256=%s" % (label, n, sha256_of(tar)))
        print("  clean2b_smoke/ files = %d (verified byte-for-byte frozen-dir artifacts)"
              % len(smoke_rels))
        print("  DIST = %s" % DIST)
    finally:
        shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    main()
