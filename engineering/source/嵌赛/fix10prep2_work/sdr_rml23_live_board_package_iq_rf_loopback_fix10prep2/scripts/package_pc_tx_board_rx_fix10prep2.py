"""Package the fix10prep2 delivery: PC-TX / Board-RX real dual-SDR topology.

fix10prep2 sits on top of the accumulated h5 authoritative tree (NOT the fix10-prep
h2 baseline) and adds ONE auditable path:

  Windows PC owns the TX SDR (periodically emits the frozen CI16 training-frame burst
  over 50-ohm coax)  <-TCP control + identity only->  board owns the RX SDR
  (capture -> CFO/sync/gain recovery -> D2 restore -> NPU24 -> 24->23 merge ->
  frozen-baseline comparison).

No real-time IQ crosses the network; the pure-digital IQ path, the single-SDR recovery
core, the model, weights, labels, preprocess and 24->23 mapping are all UNCHANGED.

The change set (the ONLY thing the patch carries):
  * PC TX service + protocol + WSL burst builder:
      host_tools/pc_tx_sdr_fix10.py, host_tools/fix10_tx_protocol.py,
      host_tools/build_burst_cli.cpp, host_tools/build_burst_cli.sh
  * board RX-only side (no TX API) + TCP client + state machine:
      sdr_adapter/tcp_control_client.hpp,
      board_package/iq_pc_tx_board_rx_transfer_fix10.hpp,
      board_package/iq_pc_tx_board_rx_23class_fix10.hpp
  * host tests:
      host_tests/test_pc_tx_protocol_fix10.cpp, .py,
      host_tests/test_pc_tx_board_rx_fix10.cpp, test_pc_tx_provenance_fix10.cpp
  * wiring + docs + packager:
      board_package/gate9_phase.hpp, board_package/board_gate9_full_chain_rml23.cpp,
      host_tests/build_host_tests.sh, host_tests/run_tests.sh,
      scripts/run_gate9_rml23.sh, scripts/package_pc_tx_board_rx_fix10prep2.py,
      docs/M29_RML23_FIX10PREP2_PC_TX_BOARD_RX_AUDIT.md

Produces, under dist/:
  1. sdr_rml23_live_pc_tx_board_rx_fix10prep2_patch.tar.gz
  2. sdr_rml23_live_board_package_pc_tx_board_rx_fix10prep2.tar.gz   (full tree)

Fail-closed audits the packager runs BEFORE emitting anything:
  * RED-LINE headers (iq_rf_sync_recovery.hpp, iq_rf_training_frame.hpp,
    iq_digital_loopback.hpp, iq_rf_fix9r_baseline.hpp) are byte-identical to the h5
    base -- the recovery core and frame math were not touched.
  * PROTECTED dirs (model/weights/labels/preprocess) byte-identical to h5.
  * every quoted include of every new C++ file resolves inside the tree.
  * no old-fix10 (external_rf / pluto_external) residue.

Each tarball carries a SHA256SUMS in the repo's `HASH *relpath` convention
(sha256sum -b).  stdlib only; deterministic (uid/gid 0, mtime 0, sorted entries,
gzip level 9, mtime 0).  Run with:  python scripts/package_pc_tx_board_rx_fix10prep2.py
"""

