#!/usr/bin/env python3
# generate_fix10_canonical_frame_header.py
#
# fix10prep3 Batch 2, §4.3.  Read the 3 frozen canonical training-frame components
# (contracts/fix10_canonical_frame_v1/{preamble,payload_training,tail}.ci16) and
# emit the C++17 COMPILE-TIME data header
# board_package/iq_fix10_canonical_frame_data.hpp.
#
# The 3 components are the aarch64-board-authoritative training components frozen in
# §4.2 (preamble / payload-domain gain training / tail).  The header embeds them as
# constexpr int16 arrays so BOTH the PC (build_burst_cli) and the board assemble the
# burst from the SAME bytes, making the full burst SHA cross-architecture identical
# (the root fix for READY_REJECTED burst_sha_prepared_mismatch).
#
# Determinism: fixed component order, fixed per-line value count, plain decimal
# int16, no timestamps, no path/source-arch in the body (only frozen SHAs).  Two
# runs over the same contract produce a byte-identical header.  Every array is
# verified against the manifest SHA before emission (fail-closed on mismatch).

import hashlib
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTRACT = os.path.join(ROOT, "contracts", "fix10_canonical_frame_v1")
OUT = os.path.join(ROOT, "board_package", "iq_fix10_canonical_frame_data.hpp")

# component -> {ci16 filename, array constant name, sha constant name}
COMPONENTS = [
    ("preamble", "kCanonicalPreamble", "kCanonicalPreambleSha"),
    ("payload_training", "kCanonicalPayloadTraining", "kCanonicalPayloadTrainingSha"),
    ("tail", "kCanonicalTail", "kCanonicalTailSha"),
]

EXPECTED_BYTES = 4096        # 1024 complex * 2 int16
EXPECTED_INTS = 2048
VALUES_PER_LINE = 12
CONTRACT_VERSION = 1


def fail(msg):
    sys.stderr.write("generate_fix10_canonical_frame_header: " + msg + "\n")
    sys.exit(1)


def load_component(name):
    path = os.path.join(CONTRACT, name + ".ci16")
    with open(path, "rb") as f:
        raw = f.read()
    if len(raw) != EXPECTED_BYTES:
        fail("%s: expected %d bytes, got %d" % (name, EXPECTED_BYTES, len(raw)))
    vals = struct.unpack("<%dh" % EXPECTED_INTS, raw)
    return raw, vals


def manifest_sha(name):
    path = os.path.join(CONTRACT, "manifest.tsv")
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            if line.startswith("#"):
                continue
            cols = line.rstrip("\n").split("\t")
            if len(cols) >= 8 and cols[1] == name:
                return cols[4]
    fail("%s: no row in manifest.tsv" % name)


def contract_sha():
    blob = b""
    for name, _, _ in COMPONENTS:
        with open(os.path.join(CONTRACT, name + ".ci16"), "rb") as f:
            blob += f.read()
    return hashlib.sha256(blob).hexdigest()


def fmt_array(name, vals):
    lines = []
    lines.append("// %s: %d complex (1024) as %d interleaved int16, little-endian." %
                 (name, EXPECTED_INTS // 2, EXPECTED_INTS))
    lines.append("inline constexpr std::array<std::int16_t, %d> kCanonical%s = {{"
                 % (EXPECTED_INTS, "Preamble" if name == "preamble" else
                    "PayloadTraining" if name == "payload_training" else "Tail"))
    for i in range(0, EXPECTED_INTS, VALUES_PER_LINE):
        chunk = vals[i:i + VALUES_PER_LINE]
        body = ", ".join(str(v) for v in chunk)
        tail = "," if i + VALUES_PER_LINE < EXPECTED_INTS else ""
        lines.append("    " + body + tail)
    lines.append("}};")
    return "\n".join(lines)


def main():
    raw = {}
    vals = {}
    shas = {}
    for name, arr_const, sha_const in COMPONENTS:
        r, v = load_component(name)
        raw[name] = r
        vals[name] = v
        shas[name] = hashlib.sha256(r).hexdigest()
        declared = manifest_sha(name)
        if shas[name] != declared:
            fail("%s: sha256 mismatch (file %s, manifest %s)" %
                 (name, shas[name], declared))
    csha = contract_sha()

    header = []
    header.append("// iq_fix10_canonical_frame_data.hpp -- GENERATED by")
    header.append("// scripts/generate_fix10_canonical_frame_header.py.  DO NOT EDIT BY HAND.")
    header.append("//")
    header.append("// fix10prep3: canonical (aarch64-authoritative) training-frame components")
    header.append("// embedded at compile time so the PC and the board assemble the SAME burst")
    header.append("// bytes.  contract_version=%d, contract_sha=%s." % (CONTRACT_VERSION, csha))
    header.append("//")
    header.append("#pragma once")
    header.append("")
    header.append("#include <array>")
    header.append("#include <cstddef>")
    header.append("#include <cstdint>")
    header.append("")
    header.append("namespace fix10canonical {")
    header.append("")
    header.append("inline constexpr std::size_t kCanonicalComponentComplex = 1024;")
    header.append("inline constexpr std::size_t kCanonicalComponentInt16 = 2048;")
    header.append("inline constexpr int kCanonicalContractVersion = %d;" % CONTRACT_VERSION)
    header.append("")
    for name, arr_const, sha_const in COMPONENTS:
        header.append(fmt_array(name, vals[name]))
        header.append("")
    for name, arr_const, sha_const in COMPONENTS:
        header.append('inline constexpr const char* %s = "%s";' % (sha_const, shas[name]))
    header.append('inline constexpr const char* kCanonicalContractSha = "%s";' % csha)
    header.append("")
    header.append("}  // namespace fix10canonical")
    header.append("")

    text = "\n".join(header)
    # Newline-normalize to LF only for a byte-stable artifact regardless of host OS.
    text = text.replace("\r\n", "\n")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)

    sys.stdout.write(
        "generated %s\n"
        "  preamble_sha          = %s\n"
        "  payload_training_sha  = %s\n"
        "  tail_sha              = %s\n"
        "  contract_sha          = %s\n"
        "  bytes                 = %d\n" %
        (os.path.relpath(OUT, ROOT), shas["preamble"], shas["payload_training"],
         shas["tail"], csha, len(text)))


if __name__ == "__main__":
    main()
