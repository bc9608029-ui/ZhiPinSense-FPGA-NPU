#!/usr/bin/env python3
"""Generate the symmetric-Hann Q1.15 coefficient ROM for the FPGA window framer.

Produces `rtl/hann_coeff_q15.v` (a `reg [15:0] hann_coeff [0:1023]` array with an
`initial` block) and self-checks that the emitted table is byte-identical to the
frozen Golden `hann_q15(1024)` in `reference/smart_scan_golden.py`. The exact
formula is `clip(round_away(np.hanning(1024) * 2**15), -32768, 32767)`, i.e. the
same "ties away from zero" rounding used by the RTL `round15` (add 2**14, then
arithmetic-shift right by 15).
"""
from __future__ import annotations
import importlib.util
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def round_away(x):
    x = float(x)
    return int((x / abs(x)) * (abs(x) + 0.5)) if x != 0.0 else 0
    # equivalent to sign * floor(|x|+0.5); np handled via math below instead.


def _load_golden_hann():
    spec = importlib.util.spec_from_file_location(
        "smart_scan_golden", os.path.join(ROOT, "reference", "smart_scan_golden.py")
    )
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.hann_q15


def main():
    golden_hann = _load_golden_hann()
    golden = golden_hann(1024).astype(int).tolist()

    # Recompute independently (no numpy float rounding ambiguity) and cross-check.
    import math
    n = 1024
    mine = []
    for k in range(n):
        # np.hanning symmetric: 0.5 - 0.5*cos(2*pi*k/(n-1))
        w = 0.5 - 0.5 * math.cos(2.0 * math.pi * k / (n - 1))
        v = w * (1 << 15)
        # round half away from zero
        r = math.floor(abs(v) + 0.5) * (1 if v >= 0 else -1)
        r = max(-32768, min(32767, r))
        mine.append(r)

    if mine != golden:
        raise SystemExit(
            "Hann table mismatch against Golden: first diff at "
            f"{next(i for i in range(n) if mine[i] != golden[i])}"
        )

    out_path = os.path.join(ROOT, "rtl", "hann_coeff_rom.v")
    lines = [
        "`timescale 1ns/1ps",
        "// Symmetric Hann window ROM, Q1.15 (generated by scripts/generate_hann_table.py).",
        "// Frozen formula: clip(round_away(np.hanning(1024) * 2**15), -32768, 32767),",
        "// byte-identical to reference/smart_scan_golden.py hann_q15(1024).",
        "// k==0 and k==1023 are zero; the peak bin (k==511) saturates to 32767.",
        "// Do not hand-edit; regenerate with:  python scripts/generate_hann_table.py",
        "",
        "module hann_coeff_rom (",
        "    input  wire [9:0]  addr,",
        "    output reg  [15:0] dout",
        ");",
        "    reg [15:0] mem [0:1023];",
        "    initial begin",
    ]
    # Wrap 8 values per line for readability.
    for base in range(0, n, 8):
        chunk = " ".join(f"mem[{i}] = 16'sd{v};" for i, v in enumerate(mine[base:base + 8], start=base))
        lines.append("        " + chunk)
    lines.append("    end")
    lines.append("    always @(*) dout = mem[addr];")
    lines.append("endmodule")
    lines.append("")

    with open(out_path, "w", newline="\n") as f:
        f.write("\n".join(lines))

    print(f"HANN_TABLE_GENERATE result=PASS n={n} first={mine[0]} mid={mine[511]} last={mine[-1]}")
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
