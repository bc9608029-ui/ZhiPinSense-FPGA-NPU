"""Deterministic M20 package builder (12-class OOD-U / UNKNOWN rejection).

Builds two versioned, deterministic archives under ``dist/``:

* ``m20_12class_ood_u_patch.tar.gz`` — the M20 **delta** (net-new files only,
  relative to the inherited RML24 V1.1 base): ``ood_u/``, ``cpp/`` (source only,
  no built binaries), ``tools/``, ``scripts/m20_*.py``, ``scripts/run_m20_*.sh`` +
  ``test_m20_ood_u.sh``, ``tests/test_m20_*.py``, ``docs/M20_*.md`` and the frozen
  ``model_12class/`` deployment assets.
* ``sdr_amr_12class_ood_u_m20_package.tar.gz`` — the full self-contained project
  source (inherited base + M20), machine-local / regenerated artifacts excluded.

Both use a fixed gzip mtime, owner 0, stable file ordering, and carry a sorted
``SHA256SUMS.txt``.  Built C++ binaries, ``runs/``, caches and ``.npz``/``audit.json``
are excluded (regenerated on the target by ``run_data_audit.sh`` /
``test_m20_ood_u.sh`` / ``cpp/build_ood_u.sh``).
"""

from __future__ import annotations

import gzip
import hashlib
import io
import json
import tarfile
from pathlib import Path
from typing import Iterable

PROJECT_ROOT = Path(__file__).resolve().parents[1]
PATCH_NAME = "m20_12class_ood_u_patch"
FULL_NAME = "sdr_amr_12class_ood_u_m20_package"
MTIME = 0

# --- Patch (M20 delta) file set -------------------------------------------
# Every M20 net-new source file, relative to PROJECT_ROOT.  Built binaries are
# deliberately omitted (regenerated by cpp/build_ood_u.sh).


def _patch_files() -> list[str]:
    files: list[str] = []
    for sub in ("ood_u/*.py", "cpp/*.hpp", "cpp/*.cpp", "cpp/*.sh",
                "tools/*", "scripts/m20_*.py", "scripts/run_m20_*.sh",
                "scripts/test_m20_ood_u.sh", "tests/test_m20_*.py",
                "docs/M20_*.md"):
        files.extend(
            str(p.relative_to(PROJECT_ROOT)).replace("\\", "/")
            for p in sorted(PROJECT_ROOT.glob(sub))
            if p.is_file() and "__pycache__" not in p.parts
        )
    files.extend(
        f"model_12class/{name}" for name in (
            "MODEL_DEPLOYMENT_CONTRACT.md",
            "ad_amr_v1_1_opset17.onnx",
            "model_12class.json",
            "model_12class.raw",
            "seed2026_best.pt",
        )
    )
    # Built C++ binaries (no extension) are never matched by the *.cpp/*.hpp/*.sh
    # globs above; keep an exact-set guard anyway so they can never slip in.
    cpp_binaries = {
        "cpp/ood_u_replay", "cpp/ood_u_replay.exe",
        "cpp/test_ood_u_detector", "cpp/test_ood_u_detector.exe",
        "cpp/test_ood_u_detector_san", "cpp/test_ood_u_detector_san.exe",
    }
    # The final report is the delivery summary *about* the archives; it stays out
    # of the archives so its §十八 SHA256/file-count figures are exact and stable
    # (a self-referential archive SHA would be wrong by construction).
    files = [f for f in files if f not in cpp_binaries
             and f != "docs/M20_FINAL_REPORT.md"]
    return sorted(set(files))


# --- Full package exclusions ----------------------------------------------
EXCLUDE_DIRS = {"__pycache__", ".git", ".pytest_cache", "runs", "dist",
                "exports", "outputs", "manifests", "build"}
EXCLUDE_SUFFIXES = {".pyc", ".pyo", ".hdf5", ".npz"}
EXCLUDE_RELATIVE = {
    "data/radioml2018/audit.json",
    # Delivery summary about the archives — kept out so its §18 SHA/count are exact.
    "docs/M20_FINAL_REPORT.md",
    # Built C++ binaries (regenerated by cpp/build_ood_u.sh).
    "cpp/ood_u_replay", "cpp/ood_u_replay.exe",
    "cpp/test_ood_u_detector", "cpp/test_ood_u_detector.exe",
    "cpp/test_ood_u_detector_san", "cpp/test_ood_u_detector_san.exe",
}


def _full_files() -> list[str]:
    files: list[str] = []
    for path in sorted(PROJECT_ROOT.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(PROJECT_ROOT)
        if any(part in EXCLUDE_DIRS for part in rel.parts):
            continue
        if path.suffix.lower() in EXCLUDE_SUFFIXES:
            continue
        key = str(rel).replace("\\", "/")
        if key in EXCLUDE_RELATIVE:
            continue
        if rel.name == "SHA256SUMS.txt":
            continue
        files.append(key)
    return sorted(files)


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _archive_sha(path: Path) -> str:
    return _sha256(path)


def _write_archive(archive: Path, name: str, files: list[str]) -> dict[str, object]:
    missing = [f for f in files if not (PROJECT_ROOT / f).is_file()]
    if missing:
        raise RuntimeError(f"package files missing: {missing}")
    sums: list[str] = []
    with archive.open("wb") as raw:
        with gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=MTIME) as gz:
            with tarfile.open(fileobj=gz, mode="w") as tar:
                for rel in files:
                    path = PROJECT_ROOT / rel
                    digest = _sha256(path)
                    sums.append(f"{digest}  {rel}\n")
                    info = tar.gettarinfo(str(path), arcname=f"{name}/{rel}")
                    info.mtime = MTIME
                    info.uid = 0
                    info.gid = 0
                    info.uname = ""
                    info.gname = ""
                    with path.open("rb") as handle:
                        tar.addfile(info, handle)
                blob = "".join(sorted(sums)).encode("utf-8")
                sums_info = tarfile.TarInfo(name=f"{name}/SHA256SUMS.txt")
                sums_info.size = len(blob)
                sums_info.mtime = MTIME
                sums_info.uid = 0
                sums_info.gid = 0
                sums_info.uname = ""
                sums_info.gname = ""
                tar.addfile(sums_info, io.BytesIO(blob))
    return {
        "archive": str(archive),
        "archive_sha256": _archive_sha(archive),
        "size_bytes": archive.stat().st_size,
        "n_files": len(files) + 1,  # + SHA256SUMS.txt
    }


def _verify(archive: Path, name: str) -> None:
    import subprocess
    import sys
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        with tarfile.open(archive, "r:gz") as tar:
            tar.extractall(root, filter="data")
        base = root / name
        manifest = sorted((base / "SHA256SUMS.txt").read_text(encoding="utf-8").splitlines())
        failures = 0
        for line in manifest:
            expected, _, rel = line.partition("  ")
            actual = _sha256(base / rel)
            if actual != expected:
                failures += 1
                print(f"MISMATCH {rel}: expected {expected} got {actual}", file=sys.stderr)
        if failures:
            raise RuntimeError(f"{name} verification failed: {failures} mismatches")


def build(out_dir: Path) -> dict[str, object]:
    out_dir.mkdir(parents=True, exist_ok=True)
    patch = _write_archive(out_dir / f"{PATCH_NAME}.tar.gz", PATCH_NAME, _patch_files())
    _verify(out_dir / f"{PATCH_NAME}.tar.gz", PATCH_NAME)
    patch["verify"] = "ok"

    full = _write_archive(out_dir / f"{FULL_NAME}.tar.gz", FULL_NAME, _full_files())
    _verify(out_dir / f"{FULL_NAME}.tar.gz", FULL_NAME)
    full["verify"] = "ok"
    return {"patch": patch, "full": full}


def main() -> None:
    import argparse

    parser = argparse.ArgumentParser()
    parser.add_argument("--out-dir", default="dist")
    args = parser.parse_args()
    print(json.dumps(build(Path(args.out_dir)), indent=2))


if __name__ == "__main__":
    main()
