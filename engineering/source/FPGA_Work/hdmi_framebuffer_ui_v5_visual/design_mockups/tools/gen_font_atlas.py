#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# gen_font_atlas.py — 生成板端 C++ 字体图集 font_atlas_data.cpp
#
# 复用 make_mockups.py 的 FontAtlas（同一套 FreeType 预栅格化数学），把 DejaVu Sans
# 预栅格化为 8-bit 灰度覆盖率，输出为 C++ 静态数据。板端无 FreeType，只做 RGB565
# 整数 alpha blend（见 font_atlas.cpp）。bitmap 宽度 == advance（与设计稿一致）。
#
# 字符集 = 可打印 ASCII 32..126（95 字模）。字号矩阵：regular/bold/mono 各四档
# 20/28/40/52，另加 bold 24（底部导航与图例）。
import os
import make_mockups as mm

TOOLS = os.path.dirname(os.path.abspath(__file__))
SW = os.path.normpath(os.path.join(TOOLS, '..', '..', 'sw'))
OUT = os.path.join(SW, 'font_atlas_data.cpp')

WEIGHT_NAME = {'r': 'R', 'b': 'B', 'm': 'M'}
WEIGHT_CPP = {'r': 'Weight::Regular', 'b': 'Weight::Bold', 'm': 'Weight::Mono'}
WEIGHT_LABEL = {'r': 'regular', 'b': 'bold', 'm': 'mono'}

FONTS = [
    ('r', 20), ('r', 28), ('r', 40), ('r', 52),
    ('b', 20), ('b', 24), ('b', 28), ('b', 40), ('b', 52),
    ('m', 20), ('m', 28), ('m', 40), ('m', 52),
]

def c_name(w, s):
    return 'F_%s_%d' % (WEIGHT_NAME[w], s)

def main():
    atlas = {}
    for w, s in FONTS:
        a = mm.F(w, s)
        glyphs = []
        data = bytearray()
        for code in range(32, 127):
            cov, adv = a.glyph(chr(code))
            off = len(data)
            data += cov.tobytes()
            glyphs.append((off, adv))
        atlas[(w, s)] = (a, glyphs, bytes(data))

    L = []
    L.append('// font_atlas_data.cpp — GENERATED by design_mockups/tools/gen_font_atlas.py. DO NOT EDIT.')
    L.append('//')
    L.append('// DejaVu Sans (Regular/Bold/Mono), Bitstream Vera license — retained in')
    L.append('// design_mockups/assets/fonts/LICENSE-DejaVu.txt. Each glyph is pre-rasterized to')
    L.append('// 8-bit grayscale coverage on the PC; the board does NO FreeType and only performs')
    L.append('// RGB565 integer alpha blend (see font_atlas.cpp).')
    L.append('//')
    L.append('// Charset = printable ASCII 32..126 (95 glyphs). bitmap width == advance.')
    L.append('')
    L.append('#include "font_atlas.hpp"')
    L.append('')
    L.append('namespace ui {')
    L.append('')

    for w, s in FONTS:
        a, glyphs, data = atlas[(w, s)]
        nm = c_name(w, s)
        L.append('// %s %dpx  (ascent=%d descent=%d line_h=%d space_adv=%d)' % (
            WEIGHT_LABEL[w], s, a.ascent, a.descent, a.line_h, glyphs[0][1]))
        L.append('static const std::uint8_t DATA_%s[] = {' % nm)
        for i in range(0, len(data), 24):
            chunk = data[i:i + 24]
            L.append('  ' + ','.join('0x%02X' % b for b in chunk) + ',')
        L.append('};')
        L.append('static const glyph_t GLYPHS_%s[95] = {' % nm)
        for i in range(0, 95, 4):
            row = glyphs[i:i + 4]
            L.append('  ' + ','.join('{%d,%d}' % (off, adv) for off, adv in row) + ',')
        L.append('};')
        L.append('static const font_t %s = { DATA_%s, GLYPHS_%s, %d, %d, %d, %d, %d };' % (
            nm, nm, nm, a.line_h, a.ascent, a.descent, s, glyphs[0][1]))
        L.append('')

    L.append('namespace {')
    L.append('struct font_entry { Weight w; int size; const font_t* f; };')
    L.append('static const font_entry FONT_TABLE[] = {')
    for w, s in FONTS:
        L.append('    {%s, %d, &%s},' % (WEIGHT_CPP[w], s, c_name(w, s)))
    L.append('};')
    L.append('} // namespace')
    L.append('')
    L.append('const font_t* font_get(Weight w, int size) {')
    L.append('    for (const auto& e : FONT_TABLE)')
    L.append('        if (e.w == w && e.size == size) return e.f;')
    L.append('    return nullptr;')
    L.append('}')
    L.append('')
    L.append('} // namespace ui')
    L.append('')

    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(L))

    total = sum(len(d) for _, _, d in atlas.values())
    print('generated %s  (%d fonts, %d bytes glyph data)' % (OUT, len(FONTS), total))

if __name__ == '__main__':
    main()
