"""Synthetic OOD modulation generator for the shared 12/24-class OOD framework.

This is a *separate* net-new module (the verbatim ``modulation_generator.py`` is
left byte-identical).  It adds the modulations missing from the deployment
generator so the near/far OOD families can be produced deterministically with the
same SeedSequence-compatible rng style.

Every added modulation is a reasonable synthetic approximation (documented as
such) — the goal is a deterministic, distinct OOD family, not a standard-exact
waveform.
"""

from __future__ import annotations

from typing import Any

import numpy as np
from scipy import signal

from datasets.modulation_generator import SignalConfig, generate_iq, root_raised_cosine_taps

# 24-class-only modulations -> near OOD for the 12-class model.
OOD_NEAR_12 = (
    "8ASK", "16PSK", "32PSK", "16APSK", "32APSK", "64APSK", "128APSK",
    "32QAM", "128QAM", "256QAM", "OQPSK", "AM-SSB-WC", "AM-SSB-SC",
)

# 12-class-only modulations -> near OOD for the 24-class model.
OOD_NEAR_24 = ("2FSK", "GFSK", "OFDM")

# Far OOD (shared by both models).
OOD_FAR = ("LFM", "CW", "MULTITONE", "PULSE", "FHOP")

# Ambiguous near-equivalents (excluded from the main OOD metrics).
OOD_AMBIGUOUS = ("AM-DSB", "WBFM", "FM", "GMSK")

# Modulations generated by the base (verbatim) generator; everything else here is new.
_BASE_MODULATIONS = {"2FSK", "GFSK", "OFDM", "CPFSK", "AM-DSB", "WBFM"}


def _gray_pam_levels(bits: int) -> np.ndarray:
    size = 2 ** bits
    binary = np.arange(size)
    gray = binary ^ (binary >> 1)
    levels = np.arange(-(size - 1), size, 2, dtype=np.float64)
    result = np.empty(size, dtype=np.float64)
    result[gray] = levels
    return result


def _normalize_rms(iq: np.ndarray, amplitude: float) -> np.ndarray:
    rms = np.sqrt(np.mean(np.abs(iq) ** 2))
    if rms <= np.finfo(np.float64).eps:
        raise ValueError("Generated OOD waveform has zero power")
    return iq * (amplitude / rms)


def _rect_qam_points(points: int) -> np.ndarray:
    """Near-square rectangular QAM constellation for 32/128/256 QAM."""
    if points == 32:
        m, n = 4, 8
    elif points == 128:
        m, n = 8, 16
    elif points == 256:
        m, n = 16, 16
    else:
        raise ValueError(f"no rectangular QAM layout for {points}")
    i_levels = _gray_pam_levels(int(np.log2(m)))
    q_levels = _gray_pam_levels(int(np.log2(n)))
    pts = np.array([a + 1j * b for b in q_levels for a in i_levels], dtype=np.complex128)
    return pts / np.sqrt(np.mean(np.abs(pts) ** 2))


def _apsk_points(points: int) -> np.ndarray:
    """Synthetic multi-ring APSK (not a specific standard)."""
    ring_counts = {
        16: [4, 12],
        32: [4, 12, 16],
        64: [4, 12, 20, 28],
        128: [4, 12, 20, 28, 64],
    }[points]
    radii = [0.45, 1.0, 1.6, 2.2, 2.9][: len(ring_counts)]
    pts: list[np.complex128] = []
    for ring, (count, radius) in enumerate(zip(ring_counts, radii)):
        offset = 0.0 if ring == 0 else np.pi / count
        pts.extend(radius * np.exp(1j * (2.0 * np.pi * np.arange(count) / count + offset)))
    result = np.array(pts, dtype=np.complex128)
    return result / np.sqrt(np.mean(np.abs(result) ** 2))


def constellation_points_ood(modulation: str) -> np.ndarray:
    """Normalized constellation for the newly added linear modulations."""
    modulation = modulation.upper()
    if modulation == "8ASK":
        return _gray_pam_levels(3) / np.sqrt(np.mean(_gray_pam_levels(3) ** 2))
    if modulation in {"16PSK", "32PSK"}:
        return np.exp(1j * 2.0 * np.pi * np.arange(int(modulation[:2])) / int(modulation[:2]))
    if modulation in {"32QAM", "128QAM", "256QAM"}:
        return _rect_qam_points(int(modulation.replace("QAM", "")))
    raise ValueError(f"{modulation} has no OOD constellation")


def _pulse_shaped(symbols: np.ndarray, cfg: SignalConfig, timing_offset: int) -> np.ndarray:
    taps = root_raised_cosine_taps(cfg.samples_per_symbol, cfg.span_symbols, cfg.rolloff)
    shaped = signal.upfirdn(taps, symbols, up=cfg.samples_per_symbol)
    group_delay = (len(taps) - 1) // 2
    start = group_delay + cfg.span_symbols * cfg.samples_per_symbol + timing_offset
    cropped = shaped[start: start + cfg.sample_length]
    if len(cropped) < cfg.sample_length:
        cropped = np.pad(cropped, (0, cfg.sample_length - len(cropped)))
    return cropped.astype(np.complex128, copy=False)


def _bandlimited_message(rng: np.random.Generator, length: int,
                         sample_rate: float, bandwidth_hz: float) -> np.ndarray:
    guard = 256
    white = rng.standard_normal(length + 2 * guard)
    taps = signal.firwin(129, bandwidth_hz, fs=sample_rate, window="hann")
    message = signal.lfilter(taps, [1.0], white)[guard: guard + length]
    message -= float(np.mean(message))
    peak = float(np.max(np.abs(message)))
    if peak <= np.finfo(np.float64).eps:
        raise ValueError("generated analog message has zero amplitude")
    return message / peak


def _linear_ood(modulation: str, rng: np.random.Generator, cfg: SignalConfig) -> tuple[np.ndarray, dict[str, Any]]:
    timing_offset = int(rng.integers(0, cfg.samples_per_symbol))
    points = constellation_points_ood(modulation)
    symbol_count = int(np.ceil((cfg.sample_length + timing_offset) / cfg.samples_per_symbol)) + 2 * cfg.span_symbols + 4
    symbols = points[rng.integers(0, len(points), size=symbol_count)]
    iq = _pulse_shaped(symbols, cfg, timing_offset)
    return iq, {
        "constellation_size": len(points),
        "record_timing_offset_samples": timing_offset,
        "occupied_bandwidth_hz_approx": (1.0 + cfg.rolloff) * cfg.symbol_rate,
    }


def _generate_apsk(modulation: str, rng: np.random.Generator, cfg: SignalConfig) -> tuple[np.ndarray, dict[str, Any]]:
    timing_offset = int(rng.integers(0, cfg.samples_per_symbol))
    points = _apsk_points(int(modulation.replace("APSK", "")))
    symbol_count = int(np.ceil((cfg.sample_length + timing_offset) / cfg.samples_per_symbol)) + 2 * cfg.span_symbols + 4
    symbols = points[rng.integers(0, len(points), size=symbol_count)]
    iq = _pulse_shaped(symbols, cfg, timing_offset)
    return iq, {"constellation_size": len(points), "record_timing_offset_samples": timing_offset}


def _generate_oqpsk(rng: np.random.Generator, cfg: SignalConfig) -> tuple[np.ndarray, dict[str, Any]]:
    sps = cfg.samples_per_symbol
    timing_offset = int(rng.integers(0, sps))
    symbol_count = int(np.ceil((cfg.sample_length + timing_offset) / sps)) + 2 * cfg.span_symbols + 4
    symbols = np.exp(1j * 2.0 * np.pi * rng.integers(0, 4, size=symbol_count) / 4.0) / np.sqrt(2.0)
    i_stream = np.repeat(symbols.real, sps)
    q_stream = np.repeat(symbols.imag, sps)
    # Offset the Q channel by half a symbol period.
    q_stream = np.concatenate((np.zeros(sps // 2, dtype=np.float64), q_stream))[: len(i_stream)]
    baseband = (i_stream + 1j * q_stream).astype(np.complex128)
    taps = root_raised_cosine_taps(sps, cfg.span_symbols, cfg.rolloff)
    shaped = signal.upfirdn(taps, baseband, up=1)
    group_delay = (len(taps) - 1) // 2
    start = group_delay + cfg.span_symbols * sps + timing_offset
    cropped = shaped[start: start + cfg.sample_length]
    if len(cropped) < cfg.sample_length:
        cropped = np.pad(cropped, (0, cfg.sample_length - len(cropped)))
    return cropped.astype(np.complex128), {"oqpsk": True, "record_timing_offset_samples": timing_offset}


def _generate_am_ssb(rng: np.random.Generator, cfg: SignalConfig,
                      with_carrier: bool) -> tuple[np.ndarray, dict[str, Any]]:
    bandwidth = float(rng.uniform(2500.0, 7000.0))
    index = float(rng.uniform(0.35, 0.9))
    message = _bandlimited_message(rng, cfg.sample_length, cfg.sample_rate, bandwidth)
    hilbert = signal.hilbert(message)
    ssb = (message + 1j * hilbert.imag).astype(np.complex128)  # upper sideband analytic
    iq = (1.0 + index * ssb) if with_carrier else (index * ssb)
    return iq, {
        "message_bandwidth_hz": bandwidth,
        "modulation_index": index,
        "sideband": "upper",
        "carrier": "with" if with_carrier else "suppressed",
    }


def _generate_narrow_fm(rng: np.random.Generator, cfg: SignalConfig) -> tuple[np.ndarray, dict[str, Any]]:
    """Narrowband FM (near-equivalent to RadioML ``FM``, distinct from WBFM)."""
    bandwidth = float(rng.uniform(2500.0, 7000.0))
    deviation = float(rng.uniform(2000.0, 8000.0))
    message = _bandlimited_message(rng, cfg.sample_length, cfg.sample_rate, bandwidth)
    phase_step = 2.0 * np.pi * deviation * message / cfg.sample_rate
    initial_phase = float(rng.uniform(-np.pi, np.pi))
    phase = initial_phase + np.concatenate(([0.0], np.cumsum(phase_step[:-1])))
    return np.exp(1j * phase), {
        "message_bandwidth_hz": bandwidth,
        "frequency_deviation_hz": deviation,
        "fm_kind": "narrow",
    }


def _generate_gmsk(rng: np.random.Generator, cfg: SignalConfig) -> tuple[np.ndarray, dict[str, Any]]:
    """GMSK (Gaussian MSK: BT=0.3, h=0.5) — near-equivalent to GFSK."""
    timing_offset = int(rng.integers(0, cfg.samples_per_symbol))
    span_symbols = 4
    symbol_count = int(np.ceil((cfg.sample_length + timing_offset) / cfg.samples_per_symbol)) + 2 * span_symbols + 2
    symbols = 2.0 * rng.integers(0, 2, size=symbol_count) - 1.0
    nrz = np.repeat(symbols, cfg.samples_per_symbol)
    bt = 0.3
    tap_count = 2 * span_symbols * cfg.samples_per_symbol + 1
    sigma = max(cfg.samples_per_symbol / (2.0 * np.pi * bt), 1.0)
    taps = signal.windows.gaussian(tap_count, std=sigma)
    taps = taps / np.sum(taps)
    shaped = signal.fftconvolve(nrz, taps, mode="same")
    start = span_symbols * cfg.samples_per_symbol + timing_offset
    shaped = shaped[start: start + cfg.sample_length]
    modulation_index = 0.5
    frequency = shaped * modulation_index * cfg.symbol_rate / 2.0
    phase_step = 2.0 * np.pi * frequency / cfg.sample_rate
    initial_phase = float(rng.uniform(-np.pi, np.pi))
    phase = initial_phase + np.concatenate(([0.0], np.cumsum(phase_step[:-1])))
    return np.exp(1j * phase), {"bt": bt, "modulation_index": modulation_index, "gmsk": True}


def _generate_lfm(rng: np.random.Generator, cfg: SignalConfig) -> tuple[np.ndarray, dict[str, Any]]:
    n = cfg.sample_length
    t = np.arange(n, dtype=np.float64) / cfg.sample_rate
    f0 = float(rng.uniform(-0.3, 0.1) * cfg.sample_rate)
    f1 = float(rng.uniform(0.1, 0.3) * cfg.sample_rate)
    k = (f1 - f0) / (n / cfg.sample_rate)
    phase = 2.0 * np.pi * (f0 * t + 0.5 * k * t ** 2) + float(rng.uniform(-np.pi, np.pi))
    return np.exp(1j * phase), {"start_hz": f0, "stop_hz": f1, "chirp_rate": k}


def _generate_cw(rng: np.random.Generator, cfg: SignalConfig) -> tuple[np.ndarray, dict[str, Any]]:
    n = np.arange(cfg.sample_length, dtype=np.float64)
    f0 = float(rng.uniform(-0.4, 0.4) * cfg.sample_rate)
    phase0 = float(rng.uniform(-np.pi, np.pi))
    iq = np.exp(1j * (2.0 * np.pi * f0 * n / cfg.sample_rate + phase0))
    return iq, {"frequency_hz": f0}


def _generate_multitone(rng: np.random.Generator, cfg: SignalConfig) -> tuple[np.ndarray, dict[str, Any]]:
    n = np.arange(cfg.sample_length, dtype=np.float64)
    count = int(rng.integers(3, 8))
    iq = np.zeros(cfg.sample_length, dtype=np.complex128)
    frequencies = []
    for _ in range(count):
        f = float(rng.uniform(-0.4, 0.4) * cfg.sample_rate)
        phase = float(rng.uniform(-np.pi, np.pi))
        amp = float(rng.uniform(0.3, 1.0))
        iq += amp * np.exp(1j * (2.0 * np.pi * f * n / cfg.sample_rate + phase))
        frequencies.append(f)
    return iq, {"num_tones": count, "frequencies_hz": frequencies}


def _generate_pulse(rng: np.random.Generator, cfg: SignalConfig) -> tuple[np.ndarray, dict[str, Any]]:
    n = cfg.sample_length
    period = int(rng.integers(32, 128))
    duty = float(rng.uniform(0.1, 0.5))
    on = (np.arange(n) % period) < int(duty * period)
    f0 = float(rng.uniform(-0.3, 0.3) * cfg.sample_rate)
    carrier = np.exp(1j * (2.0 * np.pi * f0 * np.arange(n) / cfg.sample_rate))
    return (on * carrier).astype(np.complex128), {"period": period, "duty": duty, "frequency_hz": f0}


def _generate_fhop(rng: np.random.Generator, cfg: SignalConfig) -> tuple[np.ndarray, dict[str, Any]]:
    n = cfg.sample_length
    hop_len = int(rng.integers(64, 256))
    n_hops = int(np.ceil(n / hop_len)) + 1
    freqs = rng.uniform(-0.4, 0.4, size=n_hops) * cfg.sample_rate
    phase = 0.0
    segments: list[np.ndarray] = []
    idx = 0
    for h in range(n_hops):
        length = min(hop_len, n - idx)
        if length <= 0:
            break
        nn = np.arange(length, dtype=np.float64)
        seg = np.exp(1j * (2.0 * np.pi * freqs[h] * nn / cfg.sample_rate + phase))
        phase = phase + 2.0 * np.pi * freqs[h] * length / cfg.sample_rate
        segments.append(seg)
        idx += length
    iq = np.concatenate(segments)
    if len(iq) < n:
        iq = np.pad(iq, (0, n - len(iq)))
    return iq.astype(np.complex128), {"hop_len": hop_len, "n_hops": n_hops, "frequencies_hz": freqs.tolist()}


_OOD_FN = {
    "8ASK": _linear_ood, "16PSK": _linear_ood, "32PSK": _linear_ood,
    "32QAM": _linear_ood, "128QAM": _linear_ood, "256QAM": _linear_ood,
    "16APSK": _generate_apsk, "32APSK": _generate_apsk, "64APSK": _generate_apsk,
    "128APSK": _generate_apsk, "OQPSK": _generate_oqpsk,
}


def generate_ood_iq(modulation: str, config: dict[str, Any] | SignalConfig,
                    rng: np.random.Generator | None = None) -> tuple[np.ndarray, dict[str, Any]]:
    """Generate one normalized complex64 OOD IQ record + metadata.

    Delegates 2FSK/GFSK/OFDM/CPFSK/AM-DSB/WBFM to the base generator; every other
    OOD modulation is synthesized here.
    """
    modulation = modulation.upper()
    rng = rng or np.random.default_rng()
    cfg = SignalConfig.from_dict(config) if isinstance(config, dict) else config

    if modulation in _BASE_MODULATIONS:
        iq, meta = generate_iq(modulation, cfg, rng)
        meta["ood_synthesis"] = "base_generator"
        return iq, meta

    if modulation in {"AM-SSB-WC", "AM-SSB-SC"}:
        iq, extra = _generate_am_ssb(rng, cfg, modulation == "AM-SSB-WC")
    elif modulation in _OOD_FN:
        iq, extra = _OOD_FN[modulation](modulation, rng, cfg) if modulation not in {"OQPSK"} \
            else _OOD_FN[modulation](rng, cfg)
    elif modulation == "LFM":
        iq, extra = _generate_lfm(rng, cfg)
    elif modulation == "CW":
        iq, extra = _generate_cw(rng, cfg)
    elif modulation == "MULTITONE":
        iq, extra = _generate_multitone(rng, cfg)
    elif modulation == "PULSE":
        iq, extra = _generate_pulse(rng, cfg)
    elif modulation == "FHOP":
        iq, extra = _generate_fhop(rng, cfg)
    elif modulation == "FM":
        iq, extra = _generate_narrow_fm(rng, cfg)
    elif modulation == "GMSK":
        iq, extra = _generate_gmsk(rng, cfg)
    else:
        raise ValueError(f"unsupported OOD modulation {modulation}")

    iq = _normalize_rms(iq, cfg.amplitude)
    n = np.arange(cfg.sample_length, dtype=np.float64)
    rotation = np.exp(1j * (2.0 * np.pi * cfg.frequency_offset * n / cfg.sample_rate + cfg.phase_offset))
    iq = (iq * rotation).astype(np.complex64)
    metadata: dict[str, Any] = {
        "modulation": modulation,
        "sample_rate": cfg.sample_rate,
        "sample_length": cfg.sample_length,
        "amplitude_rms": cfg.amplitude,
        "ood_synthesis": "synthetic",
        **extra,
    }
    return iq, metadata


