#!/usr/bin/env python3
# gen_fir_coeffs.py -- generate anti-aliasing polyphase FIR coefficients for the
# streaming rational resampler, for each candidate board sample rate.
#
# Outputs (all from ONE run, guaranteeing C++ and Python share identical coeffs):
#   sdr_adapter/fir_coeffs.h   -- C++17 header (inline const arrays + spec table)
#   tools/fir_coeffs.json      -- same coeffs for the Python golden reference
#   tools/fir_coeffs.bin       -- raw float64 dump (reference / runtime loader)
#
# Uses radioconda python (numpy/scipy working).  Design: equiripple (remez)
# lowpass, passband 50 kHz, stopband 64 kHz (= fs_out/2), >=70 dB stopband.
# All candidates are integer decimation: up=1, down=D.
#
# Why 30.72 MHz is NOT a candidate (see docs/RESAMPLER_DESIGN.md):
#   a single-stage x240 decimation needs >6000 taps for <57 dB (remez becomes
#   numerically unstable at that narrow transition band), which is neither
#   real-time nor sufficient.  30.72 MHz is the PC-test record only.

import json
import os
import struct

import numpy as np
from scipy.signal import remez, freqz

FS_OUT = 128000           # fixed model sample rate
PASSBAND_HZ = 50_000.0    # model signal (~25 kHz) fits well below this
STOPBAND_HZ = 64_000.0    # == FS_OUT/2, output Nyquist
STOP_ATTEN_DB = 70.0
MAX_TAPS = 4096

# (name, fs_in_hz, down)  -- integer decimation, fs_in = 128000 * down.
CANDIDATES = [
    ("2p56M", 2_560_000, 20),   # preferred: AD9364 accepts 2.56M in [2.083M,61.44M]
    ("3p84M", 3_840_000, 30),   # native AD9364 rate
]

HERE = os.path.dirname(os.path.abspath(__file__))
ADAPTER_DIR = os.path.abspath(os.path.join(HERE, "..", "sdr_adapter"))


def stopband_atten(coeffs, fs_in):
    w, h = freqz(coeffs, worN=1 << 16, fs=fs_in)
    h = np.abs(h)
    idx = w >= STOPBAND_HZ
    if not np.any(idx):
        return 100.0
    return -20.0 * np.log10(np.max(h[idx]) + 1e-15)


def design(fs_in):
    # taps grow ~linearly with fs_in (empirically: 601 @ 2.56M, ~900 @ 3.84M).
    n = int(round(601.0 * fs_in / 2_560_000))
    n = n + 1 if n % 2 == 0 else n
    n = max(n, 101)
    while n <= MAX_TAPS:
        try:
            coeffs = remez(n, [0, PASSBAND_HZ, STOPBAND_HZ, fs_in / 2.0],
                           [1, 0], weight=[1.0, 20.0], fs=fs_in,
                           grid_density=32, maxiter=100)
            att = stopband_atten(coeffs, fs_in)
            if att >= STOP_ATTEN_DB:
                return n, coeffs, att
        except ValueError:
            pass  # non-convergence at this numtaps; try next
        n += 100
    raise RuntimeError(f"no FIR met {STOP_ATTEN_DB} dB under {MAX_TAPS} taps for fs_in={fs_in}")


def main():
    specs = []
    for name, fs_in, down in CANDIDATES:
        n, coeffs, att = design(fs_in)
        # Integer decimator (up=1): normalize DC gain to exactly 1.
        coeffs = coeffs / coeffs.sum()
        att_norm = stopband_atten(coeffs, fs_in)
        specs.append(dict(name=name, fs_in_hz=fs_in, up=1, down=down,
                          numtaps=n, stopband_db=round(float(att_norm), 2),
                          coeffs=[float(c) for c in coeffs]))
        print(f"[{name}] fs_in={fs_in} down={down} taps={n} stopband={att_norm:.1f} dB")

    # --- JSON (Python golden shares these exact doubles) ---
    json_path = os.path.join(HERE, "fir_coeffs.json")
    with open(json_path, "w") as f:
        json.dump(dict(fs_out_hz=FS_OUT, specs=specs), f, indent=2)
    print("wrote", json_path)

    # --- raw binary (float64, one candidate after another) ---
    bin_path = os.path.join(HERE, "fir_coeffs.bin")
    with open(bin_path, "wb") as f:
        for s in specs:
            f.write(struct.pack("=%dd" % len(s["coeffs"]), *s["coeffs"]))
    print("wrote", bin_path)

    # --- C++ header ---
    hdr_path = os.path.join(ADAPTER_DIR, "fir_coeffs.h")
    lines = []
    lines.append("#pragma once")
    lines.append("// Auto-generated by tools/gen_fir_coeffs.py -- DO NOT EDIT.")
    lines.append("// Anti-aliasing FIR coefficients for the streaming resampler.")
    lines.append("// up=1, down=D integer decimation; DC gain normalized to 1.")
    lines.append("#include <cstdint>")
    lines.append("#include <cstddef>")
    lines.append("")
    lines.append("namespace sdr {")
    lines.append("")
    lines.append("struct FirSpec {")
    lines.append("    std::uint32_t fs_in_hz;")
    lines.append("    std::uint32_t up;")
    lines.append("    std::uint32_t down;")
    lines.append("    const double* coeffs;")
    lines.append("    std::size_t n;")
    lines.append("};")
    lines.append("")

    cnames = []
    for s in specs:
        cname = f"kFir_{s['name']}"
        cnames.append(cname)
        lines.append(f"inline const double {cname}[] = {{")
        row = "    "
        for i, c in enumerate(s["coeffs"]):
            row += "%.17g" % c
            if i != len(s["coeffs"]) - 1:
                row += ", "
            if (i + 1) % 6 == 0:
                lines.append(row)
                row = "    "
        if row.strip():
            lines.append(row.rstrip())
        lines.append("};")
        lines.append("")

    lines.append("inline const FirSpec kFirSpecs[] = {")
    for cname, s in zip(cnames, specs):
        lines.append("    {%d, %d, %d, %s, %d}," % (
            s["fs_in_hz"], s["up"], s["down"], cname, s["numtaps"]))
    lines.append("};")
    lines.append("inline const std::size_t kFirSpecCount = %d;" % len(specs))
    lines.append("")
    lines.append("}  // namespace sdr")

    with open(hdr_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", hdr_path)


if __name__ == "__main__":
    main()
