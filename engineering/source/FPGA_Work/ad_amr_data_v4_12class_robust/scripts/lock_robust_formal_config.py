"""Lock the selected robustness candidate for formal (durable approval).

PROVISIONAL — this is the *deliberate* step that promotes the unique pilot
candidate to formal.  It writes ``configs/ad_amr_v1_1_data_v4_12class_robust_formal.yaml``
(based on the selected candidate, with ``robust.status: APPROVED_FOR_FORMAL`` and
``robust.final_config_approved: true``) and the durable ``FINAL_CONFIG_APPROVED``
marker recording the config SHA-256 and the post-lock release-input hash.  The
formal entrypoint refuses to run unless that marker matches the current tree.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from scripts.release_guard_v1_1_data_v4_12class_robust import release_input_hash
from training.utils import PROJECT_ROOT, load_yaml

FORMAL_CONFIG = PROJECT_ROOT / "configs/ad_amr_v1_1_data_v4_12class_robust_formal.yaml"
MARKER = PROJECT_ROOT / "outputs/ad_amr_v1_1_data_v4_12class_robust/FINAL_CONFIG_APPROVED"
SELECTED = PROJECT_ROOT / "outputs/ad_amr_v1_1_data_v4_12class_robust/pilot/selected_candidate.json"


def config_sha256(config: dict) -> str:
    return hashlib.sha256(
        json.dumps(config, sort_keys=True, ensure_ascii=False, default=str).encode("utf-8")
    ).hexdigest()


def main() -> int:
    if not SELECTED.is_file():
        raise SystemExit("pilot selection is missing; run the robustness pilot first")
    selected = json.loads(SELECTED.read_text(encoding="utf-8"))
    if not selected.get("promoted"):
        raise SystemExit("pilot did not promote a unique candidate; cannot lock for formal")
    candidate = str(selected["candidate"])
    if candidate not in {"A", "B", "C"}:
        raise SystemExit(f"unexpected selected candidate {candidate!r}")

    FORMAL_CONFIG.write_text(
        f"# AUTO-GENERATED by scripts/lock_robust_formal_config.py — do not edit by hand.\n"
        f"_base: configs/ad_amr_v1_1_data_v4_12class_robust_pilot_{candidate}.yaml\n\n"
        f"robust:\n  status: APPROVED_FOR_FORMAL\n  final_config_approved: true\n",
        encoding="utf-8",
    )

    resolved = load_yaml(FORMAL_CONFIG.relative_to(PROJECT_ROOT).as_posix())
    if not resolved.get("robust", {}).get("final_config_approved"):
        raise SystemExit("locked formal config still has final_config_approved != true")
    if resolved.get("robust", {}).get("candidate") != candidate:
        raise SystemExit("locked formal config candidate does not match the selection")

    bound_hash = release_input_hash()
    MARKER.parent.mkdir(parents=True, exist_ok=True)
    MARKER.write_text(json.dumps({
        "approved": True,
        "candidate": candidate,
        "config_path": "configs/ad_amr_v1_1_data_v4_12class_robust_formal.yaml",
        "config_sha256": config_sha256(resolved),
        "release_input_hash": bound_hash,
        "selected_checkpoint": selected.get("checkpoint"),
        "train_channel_sha256": selected.get("train_channel_sha256"),
    }, indent=2), encoding="utf-8")

    print(f"locked candidate={candidate}")
    print(f"formal_config={FORMAL_CONFIG.relative_to(PROJECT_ROOT).as_posix()}")
    print(f"config_sha256={config_sha256(resolved)}")
    print(f"release_input_hash={bound_hash}")
    print(f"marker={MARKER.relative_to(PROJECT_ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
